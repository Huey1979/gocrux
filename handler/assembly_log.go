package handler

import "github.com/sirupsen/logrus"

// ============================================================
// 引用装配（v3）的日志
//
// 单独成文件的原因：装配的 WARN 需要**可测试**（设计文档 §6.1 #2 要求
// 「必须能定位：Source 路径 / 匹配键值 / Target 标识 / 所属父记录标识」），
// 因此把日志出口抽成变量，测试可替换为捕获器断言文案内容。
//
// 与 v2 的重映射不同：v2 的失败一律让事务失败（引用解析不出即为数据错误），
// v3 对「匹配不到目标」是 **WARN + 保留旧值**（B5）—— 应用侧的发布门禁
// 负责 fail-closed，框架不越界替应用决定能否发布。
// ============================================================

// asmLogger 装配日志出口（默认 logrus.Warnf）。
//
// 抽成变量而非直接调用 logrus：测试可替换以捕获并断言 WARN 内容。
var asmLogger = func(format string, args ...any) {
	logrus.Warnf(format, args...)
}
